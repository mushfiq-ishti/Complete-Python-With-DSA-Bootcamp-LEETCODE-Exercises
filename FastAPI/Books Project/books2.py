@app.post("/create_book",status_code=status.HTTP_201_CREATED)
def create_book(book_request: BookRequest): 
    # Unpacking the values of the book request and passing them to the book constructor
    new_book = Book(**book_request.dict()) 
    
    # Finding the id for the new book
    new_book = find_book_id(new_book) 
    
    # Adding it to the list of books
    books.append(new_book)
    return {"message": "Book created successfully", "book": new_book}


def find_book_id(book: Book):
    if len(books) == 0:
        book.id = 1
    else:
        # Find the highest ID currently in the list and add 1
        # (Assuming the 'books' list contains objects that have an 'id' attribute)
        book.id = max(existing_book.id for existing_book in books) + 1
        
    return book

@app.put("/books/update_book")
def update_book(book:BookRequest):
    for i in range(len(books)):
        if books[i].id == book.id:
            books[i] = Book(**book.dict()) #unpacking the values of the book request and passing them to the book constructor
            return {"message": "Book updated successfully", "book": books[i]}
    #return {"message": "Book not found"}
    raise HTTPException(status_code=404, detail="Book not found")

@app.delete("/books/remove_book/{book_id}")
def delete_book(book_id: int = Path(gt=0)):
    for i in range(len(books)):
        if books[i].id == book_id:
            # removing the book from the list and storing it in a variable
            deleted_book = books.pop(i) 
            return {"message": "Book deleted successfully", "book": deleted_book}
            
    # This only runs if the loop finishes entirely without finding a match
    return {"message": "Book not found"}
