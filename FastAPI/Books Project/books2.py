import books

app=FastAPI()

#this time we will be using a class to represent a book instead of a dictionary as in the previous example. This will allow us to have more control over the data and also make it easier to work with the data in the future when we want to add more functionality to our API. We can also use the class to create new books and add them to our list of books.
class Book:
    id:int
    title:str
    author:str
    description:str
    rating:float
    published_date:int

    def __init__(self, id, title, author, description, rating,published_date):
        self.id = id
        self.title = title
        self.author = author
        self.description = description
        self.rating = rating
        self.published_date = published_date #default value for published date, we can change it later when we want to add functionality to update the published date of a book

