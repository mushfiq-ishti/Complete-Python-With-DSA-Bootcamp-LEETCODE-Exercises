@app.get("/books/{book_id}",status_code=status.HTTP_200_OK) #dynamic param should always eb after static ones
async def read_book(book_id: int = Path(gt=0)): #path parameter with validation, book id should be greater than 0
    for book in books:
        if (book.id) == book_id:
            return book
    #return {"message": "Book not found"}
